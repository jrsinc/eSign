// Downloadable reports: an agreement's audit trail, the system audit log, and stamped print copies.
const fs = require('fs');
const path = require('path');
const { PDFDocument, StandardFonts, rgb, degrees } = require('pdf-lib');
const { appendAuditReport, pageFrame, safe, wrap } = require('./finalize');
const { auditStamp, captionStamp } = require('./dates');
const { APP_NAME } = require('./brand');
const { encryptDocument } = require('./pdfcrypt');

const INK = rgb(0.1, 0.1, 0.1);
const GRAY = rgb(0.4, 0.4, 0.4);
const BLUE = rgb(0.13, 0.4, 0.8);
const RED = rgb(0.75, 0.1, 0.1);

const integrityLine = (r) => (r.ok
  ? `Audit trail integrity: verified, ${r.checked} entries intact in the SHA-256 hash chain${r.unsealed ? ` (+${r.unsealed} older entries recorded before sealing)` : ''}.`
  : `AUDIT TRAIL INTEGRITY FAILURE: ${r.reason} (entry ${r.brokenAt + 1}).`);

// Footer on every page: who generated the report, when, and page numbers.
function stampFooters(pdf, font, text) {
  const pages = pdf.getPages();
  pages.forEach((p, i) => {
    const { width } = p.getSize();
    p.drawText(safe(`${text}  |  Page ${i + 1} of ${pages.length}`), { x: 22, y: 20, size: 6.5, font, color: GRAY, maxWidth: width - 44 });
  });
}

// An agreement's audit trail as a standalone PDF (any status: draft, sent, completed, cancelled).
// `rangeText`: set when only the events of a time window are included ("Events from … to … (12 of 30)").
async function auditTrailPdf(doc, company, { generatedBy, integrity, rangeText = '' }) {
  const pdf = await PDFDocument.create();
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  await appendAuditReport(pdf, doc, company, { font, bold });
  // Integrity result (of the whole trail) and the time window, under the history on the last page.
  const last = pdf.getPages()[pdf.getPageCount() - 1];
  if (rangeText) last.drawText(safe(rangeText), { x: 40, y: 84, size: 8, font: bold, color: BLUE, maxWidth: 530 });
  last.drawText(safe(integrityLine(integrity)), { x: 40, y: 70, size: 8, font: bold, color: integrity.ok ? rgb(0.1, 0.5, 0.25) : RED, maxWidth: 530 });
  stampFooters(pdf, font, `Audit trail report for ${doc.agreementId || doc.title}${rangeText ? ` - ${rangeText}` : ''} - generated by ${generatedBy} on ${auditStamp(new Date().toISOString())}`);
  pdf.setTitle(`Audit trail - ${doc.title}`);
  pdf.setProducer(APP_NAME);
  return Buffer.from(await pdf.save());
}

// The system audit log (sign-ins, users, passwords, ...) as a PDF table.
async function systemLogPdf(entries, company, { generatedBy, integrity, rangeText = '' }) {
  const pdf = await PDFDocument.create();
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const logoFile = path.join(__dirname, '..', 'public', 'logo.png');
  const logo = fs.existsSync(logoFile) ? await pdf.embedPng(fs.readFileSync(logoFile)).catch(() => null) : null;
  const W = 842, H = 595, M = 36; // A4 landscape
  const cols = [[M, 120, 'When (UTC)'], [M + 125, 170, 'Who'], [M + 300, 300, 'What'], [M + 605, W - M - (M + 605), 'IP / details']];
  let page, y;
  const header = () => {
    page = pdf.addPage([W, H]);
    if (logo) {
      const s = Math.min(110 / logo.width, 28 / logo.height);
      page.drawImage(logo, { x: M, y: H - 50, width: logo.width * s, height: logo.height * s });
    }
    page.drawText('System Audit Log', { x: M + 130, y: H - 40, size: 16, font: bold, color: BLUE });
    page.drawText(safe(integrityLine(integrity)), { x: M + 130, y: H - 54, size: 7.5, font: bold, color: integrity.ok ? rgb(0.1, 0.5, 0.25) : RED });
    if (rangeText) page.drawText(safe(rangeText), { x: M + 130, y: H - 65, size: 7.5, font: bold, color: BLUE });
    y = H - (rangeText ? 82 : 75);
    cols.forEach(([x, , label]) => page.drawText(label, { x, y, size: 8, font: bold, color: INK }));
    page.drawLine({ start: { x: M, y: y - 4 }, end: { x: W - M, y: y - 4 }, thickness: 0.6, color: GRAY });
    y -= 16;
  };
  header();
  for (const e of entries) {
    const cells = [auditStamp(e.at), e.actor || '', e.text, [e.ip, e.detail].filter(Boolean).join(' - ')];
    const wrapped = cells.map((c, i) => wrap(font, c, 7.5, cols[i][1] - 6));
    const rows = Math.max(...wrapped.map((w) => w.length));
    if (y - rows * 9.5 < 45) header();
    wrapped.forEach((ls, i) => ls.forEach((l, k) => page.drawText(l, { x: cols[i][0], y: y - k * 9.5, size: 7.5, font, color: INK })));
    y -= rows * 9.5 + 5;
    page.drawLine({ start: { x: M, y: y + 3 }, end: { x: W - M, y: y + 3 }, thickness: 0.2, color: rgb(0.85, 0.85, 0.85) });
  }
  stampFooters(pdf, font, `${company} ${APP_NAME} system audit log, ${entries.length} entries${rangeText ? ` (${rangeText})` : ''}, generated by ${generatedBy} on ${auditStamp(new Date().toISOString())}`);
  pdf.setTitle('System audit log');
  pdf.setProducer(APP_NAME);
  return Buffer.from(await pdf.save());
}

// A print copy of a signed agreement: every page stamped "PRINTED COPY" with who printed it and when.
// It is a new file; the locked, digitally signed original is never changed. `sourceBytes` must be
// unencrypted (the server's plain copy of the agreement). With `protect`, the copy is locked like the
// original: printing allowed, copying text and editing not.
async function printCopyPdf(sourceBytes, doc, { printedBy, tz, verifyUrl, protect = false }) {
  const src = await PDFDocument.load(sourceBytes);
  const pdf = await PDFDocument.create();
  for (const p of await pdf.copyPages(src, src.getPageIndices())) pdf.addPage(p);
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const when = captionStamp(new Date(), tz);
  const pages = pdf.getPages();
  pages.forEach((page, i) => {
    const fr = pageFrame(page);
    const line1 = safe(`PRINTED COPY  -  ${doc.agreementId || ''}  -  Page ${i + 1} of ${pages.length}`);
    const line2 = safe(`Printed by ${printedBy} on ${when}. Uncontrolled when printed: verify the electronic original at ${verifyUrl}`);
    const size2 = Math.min(6.5, ((fr.width - 40) / Math.max(1, font.widthOfTextAtSize(line2, 6.5))) * 6.5);
    // Red-bordered box in the top margin.
    const boxW = Math.min(fr.width - 24, Math.max(bold.widthOfTextAtSize(line1, 8), font.widthOfTextAtSize(line2, size2)) + 14);
    const left = (fr.width - boxW) / 2;
    const corner = fr.map(left, 30);
    page.drawRectangle({ x: corner.x, y: corner.y, width: boxW, height: 24, rotate: fr.rotate, borderColor: RED, borderWidth: 1, color: rgb(1, 1, 1), opacity: 0.92, borderOpacity: 1 });
    const t1 = fr.map(left + 7, 15);
    page.drawText(line1, { x: t1.x, y: t1.y, size: 8, font: bold, color: RED, rotate: fr.rotate });
    const t2 = fr.map(left + 7, 25);
    page.drawText(line2, { x: t2.x, y: t2.y, size: size2, font, color: RED, rotate: fr.rotate });
    // Faint diagonal watermark across the page.
    const wm = 'PRINTED COPY';
    const wmSize = Math.min(fr.width, fr.height) / 7;
    const c = fr.map(fr.width / 2 - bold.widthOfTextAtSize(wm, wmSize) / 2.8, fr.height / 2 + wmSize);
    page.drawText(wm, { x: c.x, y: c.y, size: wmSize, font: bold, color: RED, opacity: 0.07, rotate: degrees(fr.rotate.angle + 35) });
  });
  pdf.setTitle(`${doc.title} - printed copy`);
  if (protect) encryptDocument(pdf);
  return Buffer.from(await pdf.save({ useObjectStreams: !protect }));
}

module.exports = { auditTrailPdf, systemLogPdf, printCopyPdf };
